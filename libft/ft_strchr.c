#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	int		i;
	char	target;

	i = 0;
	target = (char)c;
	while (s[i])
	{
		if (s[i] == target)
			return ((char *)&s[i]);
		i++;
	}
	if (target == '\0')
		return ((char *)&s[i]);
	return (0);
}
